const DICTS = { es, en, de };

export const lang = DICTS[document.documentElement.lang] ? document.documentElement.lang : 'es';
const dict = DICTS[lang];

/** Texto de la clave en el idioma de la página; {nombre} se sustituye por `vars.nombre`. */
export function t(key, vars) {
  const text = dict[key] ?? es[key] ?? key;
  return vars ? text.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`)) : text;
}
